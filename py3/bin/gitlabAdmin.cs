def _reportPackage() -> None:
    print("* gitlab-ce (Linux package)")
    got = subprocess.run(["dpkg-query", "-W", "-f=${Version}", "gitlab-ce"],
                         capture_output=True, text=True).stdout.strip()
    if not got:
        print("  not installed")
    elif got != gitlabInfo.version:
        print(f"  installed {got}, the pin is {gitlabInfo.version}")
    else:
        print(f"  {got} as pinned")


def _reportAccounts() -> None:
    print("* accounts (bisos.banna, the gitlab block)")
    for name in gitlabInfo.accounts:
        want = sysAccts.sysAcctOf(name).uid
        try:
            got = pwd.getpwnam(name).pw_uid
        except KeyError:
            print(f"  missing  {name}   (banna: {want})")
            continue
        print(f"  {name} {got}" + ("" if got == want else f"   differs: banna assigns {want}"))


def _exists(path) -> bool:
    """Whether path exists, also inside a directory the invoker cannot search (e.g. /etc/grafana 750)."""
    try:
        return path.exists()
    except PermissionError:
        import subprocess
        return subprocess.run(["sudo", "test", "-e", str(path)]).returncode == 0



def _reportTextDrift(livePath, generated) -> None:
    """Structured files (YAML, INI): a unified diff against the generator."""
    print(f"* {livePath}")
    if not _exists(livePath):
        print("  not installed")
        return
    liveText = pyRunAs.as_root_readFromFile(livePath)
    if not liveText:
        print(f"  cannot read {livePath}")
        return
    diff = textDrift(liveText, generated)
    if diff:
        for line in diff:
            print(f"  {line}")
    else:
        print("  agrees with the generator")


